// Verify fo-flow PROFILE-011: followers/following slide in from the side, "<" slides back
import { createRequire } from "module";
const require = createRequire(import.meta.url);
const { chromium } = require("playwright");
const BASE = "http://127.0.0.1:4173/fo-flow";
const browser = await chromium.launch();
const page = await (await browser.newContext({ viewport: { width: 440, height: 956 } })).newPage();
let failed = 0;
page.on("pageerror", e => { failed++; console.log("PAGE ERR:", e.message); });
const check = (n, ok, x = "") => { console.log(`${ok ? "PASS" : "FAIL"} ${n} ${x}`); if (!ok) failed++; };
await page.goto(`${BASE}/index.html`, { waitUntil: "networkidle" });
await page.waitForTimeout(700);
await page.locator('.bottom-nav .nav-item[data-navgo="profile"]').click();
await page.waitForTimeout(500);
await page.locator(".pf-scroll").evaluate(e => e.scrollTop = 40);
const y0 = await page.locator(".pf-scroll").evaluate(e => e.scrollTop);
await page.locator('[data-pfgo="followers"]').first().click();
await page.waitForTimeout(60);
const x = await page.locator(".page-sub").evaluate(e => e.getBoundingClientRect().left - e.parentElement.getBoundingClientRect().left);
const ghost = await page.locator(".pg-ghost").count();
check("slides in mid-animation", x > 20, `x=${x}`);
check("profile stays underneath (ghost)", ghost === 1);
await page.waitForTimeout(500);
check("list shown", await page.locator(".pfl-tabs").isVisible());
await page.locator(".sub-back").click();
await page.waitForTimeout(60);
check("ghost slides out", await page.locator(".pg-ghost.pg-out-r").count() === 1);
await page.waitForTimeout(500);
check("profile back", await page.locator('[data-pfgo="followers"]').first().isVisible());
const y1 = await page.locator(".pf-scroll").evaluate(e => e.scrollTop);
check("scroll kept", Math.abs(y1 - y0) < 2, `${y0}->${y1}`);
await browser.close();
process.exit(failed ? 1 : 0);
