import { chromium } from "playwright";
import { mkdirSync } from "fs";
import { pathToFileURL } from "url";
const FILE_URL = pathToFileURL("d:/TukDaeng/Prototypes/fo-flow/index.html").href;
const OUT = "d:/TukDaeng/Prototypes/screenshots/task-NAV-012/after2";
mkdirSync(OUT, { recursive: true });
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 1440, height: 1000 }, deviceScaleFactor: 2 });
const page = await ctx.newPage();
page.on("pageerror", e => console.log("PAGEERR", e.message));
await page.goto(FILE_URL, { waitUntil: "networkidle" });
await page.waitForTimeout(600);
const scr = page.locator(".screen").first();
const reset = async () => { await page.evaluate(() => { const s=document.querySelector(".screen"); s._subStack=[]; s.classList.remove("sub-open"); }); await page.waitForTimeout(300); };
for (const theme of ["dark", "light"]) {
  await page.evaluate(t => document.querySelector(".screen").setAttribute("data-theme", t), theme);
  await page.evaluate(() => document.querySelector(`.screen [data-navgo="board"]`).click());
  await page.waitForTimeout(500);
  await page.locator("[data-bdart]:visible").first().click(); await page.waitForTimeout(700);
  await scr.screenshot({ path: `${OUT}/boardart-${theme}.png` });
  await page.locator(".page-sub").first().evaluate(el => { const sc = el.querySelector(".sub-scroll,.bd-scroll,[class*=scroll]"); if (sc) sc.scrollTop = 300; });
  await page.waitForTimeout(300);
  await scr.screenshot({ path: `${OUT}/boardart-scrolled-${theme}.png` });
  await reset();
  await page.evaluate(() => document.querySelector(`.screen [data-navgo="chat"]`).click());
  await page.waitForTimeout(500);
  await page.locator(".ch-top-tab:visible").nth(1).click(); await page.waitForTimeout(500);
  const it = page.locator("[data-chgo='item']:visible");
  console.log("items", await it.count());
  await scr.screenshot({ path: `${OUT}/chat-items-${theme}.png` });
  await it.first().click(); await page.waitForTimeout(700);
  await scr.screenshot({ path: `${OUT}/chatitem-${theme}.png` });
  console.log("itemcard", await page.locator(".ch-itemcard:visible").count());
  await reset();
  await page.evaluate(() => document.querySelector(`.screen [data-navgo="chat"]`).click());
  await page.waitForTimeout(400);
  await page.locator(".ch-top-tab:visible").nth(0).click(); await page.waitForTimeout(400);
  await page.locator("[data-chgo='room']:visible").first().click(); await page.waitForTimeout(700);
  await scr.screenshot({ path: `${OUT}/chatroom-${theme}.png` });
  await reset();
}
await browser.close();
